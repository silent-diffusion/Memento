    [Fact]
    public async Task AFull20SessionTouchesNoNetworkAndNoVideoReachesAProvider()
    {
        var host = _host;
        await host.Settings.UpdateAsync(
            s => s with
            {
                Transcription = s.Transcription with { Timing = TranscriptionSettings.TimingDuring },
                Speakers = s.Speakers with { RememberVoices = true },
                Documents = new DocumentsSettings { OcrEngine = OcrEngines.Tesseract },
            },
            CancellationToken.None);
        Install("whisper-small", OcrEngines.TesseractEnglishModelId, "ministral-3-3b-q4");

        // Record with a screen and a camera, the live transcript listening.
        var (sessionId, id) = await host.StartAsync("Network check 2.0", Mic, FakeVideoCapture.Display1, FakeVideoCapture.Camera);
        var live = _host.Get<LiveTranscriptService>();
        host.Session.Advance(TimeSpan.FromSeconds(15));
        await host.Session.CheckpointAsync(CancellationToken.None);
        await TestRecordings.WaitUntilAsync(
            async () =>
            {
                await live.TickAsync(CancellationToken.None);
                return host.Sink.Payloads(Memento.Core.Bridge.BridgeEventNames.RecordingLiveTranscript).Any(p => p.GetProperty("segments").GetArrayLength() > 0);
            },
            "a live line");
        await ResultAsync("recording.setPip", new { sessionId, enabled = true, corner = "topLeft" });
        await ResultAsync("recording.stop", new { sessionId });
        await host.Recordings.WhenIdleAsync();
        await host.Processing.WhenIdleAsync().WaitAsync(Patience.Ceiling);
        await live.TickAsync(CancellationToken.None);

        // Known voices: learned from a named speaker, then matched.
        await host.Get<TranscriptWriter>().UpdateAsync(
            id,
            TranscriptChangeReasons.Transcribed,
            _ => Document(Segment("s1", 0, 12, "Good morning, let us start.", "spk1"), Segment("s2", 12, 28, "The numbers are in.", "spk2")),
            CancellationToken.None);
        await host.Transcripts.SaveVoicesAsync(
            id,
            new VoicesDocument(VoicesDocument.CurrentSchemaVersion, "nemo-titanet-small", "test", [], [new VoiceCluster("mic", 0, [1f, 0f, 0f], 12, ["s1"]), new VoiceCluster("mic", 1, [0f, 1f, 0f], 16, ["s2"])]),
            CancellationToken.None);
        await ResultAsync("transcript.renameSpeaker", new { recordingId = id, speakerId = "spk1", name = "Ana" });
        Assert.True((await ResultAsync("voices.remember", new { recordingId = id, speakerId = "spk1" })).GetProperty("remembered").GetBoolean());
        await ResultAsync("voices.matches", new { recordingId = id });
        await ResultAsync("voices.list", new { });

        // An agenda photo read by Tesseract in the worker.
        var photo = _directory.File("agenda.bmp");
        await File.WriteAllBytesAsync(photo, Bitmap(320, 120));
        _picker.Answer = photo;
        var agenda = await ResultAsync("agenda.importFile", new { recordingId = id });
        Assert.Contains(_jobs, j => j == WorkerJobKinds.Ocr);
        Assert.Contains("Welcome", agenda.GetRawText(), StringComparison.Ordinal);

        // A document from the local model, its preview and its copies.
        await host.Transcripts.UpdateAsync(id, TranscriptChangeReasons.Transcribed, new HistorySettings(), _ => SyntheticMeeting.Transcript(), CancellationToken.None);
        var template = await ResultAsync("templates.get", new { templateId = "meeting-minutes" });
        var preview = await ResultAsync("generation.preview", new { recordingId = id, template });
        var firstPass = preview.GetProperty("passes")[0].GetProperty("id").GetString();
        await ResultAsync("generation.copyPreview", new { recordingId = id, template, passId = firstPass });
        var start = await ResultAsync("generation.start", new { recordingId = id, template });
        var documentId = await FinishedAsync(start.GetProperty("jobId").GetString()!);
        await ResultAsync("documents.copy", new { recordingId = id, documentId });
        await ResultAsync("transcript.copy", new { recordingId = id, format = "markdown" });

        // Exports with the video, and the Review payload.
        await ResultAsync("project.get", new { recordingId = id });
        var selection = new ExportSelection
        {
            Transcript = new ExportTranscriptChoice { On = true, Formats = ["json", "markdown"] },
            Video = new ExportVideoChoice { On = true, Format = "mp4", Layout = "twoFiles" },
        };
        await ResultAsync("export.run", new { recordingId = id, selection, destination = new { folder = _directory.File("Exports"), createSubfolder = true }, remember = false });
        await _host.Get<ExportService>().WhenIdleAsync();
        await ResultAsync("library.usage", new { });

        // The session did what it says: two video tracks, a video export, the live worker and Tesseract ran.
        Assert.Equal(2, (await host.Store.LoadAsync(id, CancellationToken.None)).VideoTracks.Count);
        Assert.Contains(Directory.EnumerateFiles(_directory.File("Exports"), "*.mp4", SearchOption.AllDirectories), _ => true);
        Assert.Contains(WorkerJobKinds.Live, _jobs);
        Assert.Contains(_clipboard.Copies, c => c.Html is not null);

        Assert.Empty(_spy.Events);
        Assert.False((await host.Settings.LoadAsync(CancellationToken.None)).Ai.Enabled);
        Assert.Equal(0, _providers.CloudCreated);

        // 2.5.0: "Your own server" without an address is listed, not ready, and never built or contacted.
        var server = (await ResultAsync("providers.list", new { })).GetProperty("providers").EnumerateArray().Single(p => p.GetProperty("id").GetString() == "server");
        Assert.Equal(DomainErrorCodes.AiNoServer, server.GetProperty("code").GetString());
        Assert.Equal(0, _providers.ServerCreated);
        Assert.Empty(_spy.Events);

        // Audio and video never leave: nothing of the video is in a request, the preview or a copied preview.
        var provider = Assert.IsType<MeetingProvider>(_providers.Last);
        var sent = string.Join("\n", provider.Requests.Select(AiRequestText.Render)) + preview.GetRawText() + string.Join("\n", _clipboard.Copies.Select(c => c.Text + c.Html));
        Assert.NotEmpty(provider.Requests);
        Assert.All(VideoMarks, mark => Assert.DoesNotContain(mark, sent, StringComparison.Ordinal));
    }

    /// <summary>
    /// 2.5.0: with "Your own server" configured at a loopback address (external AI off), a generation sends exactly one
    /// request per pass to that address (the Live output's requests, one for one) and contacts nothing else: no other
    /// request, no other connect, no name lookup. The server is a fake Ollama on 127.0.0.1 answering for the synthetic
    /// meeting; the provider is the real one over the shared client.
    /// </summary>
    [Fact]
    public async Task AServerOnThisPcGetsExactlyOneRequestPerPassAndNothingElseIsContacted()
    {
        using var server = new FakeOpenAiCompatibleServer(ServerPersonality.Ollama) { Answer = MeetingAnswer };
        using var http = new AiHttpClient();
        _providers.MakeServer = options => new ServerProvider(http.Client, _host.Get<ISecretReader>(), options, NullLogger<ServerProvider>.Instance);
        var id = await MeetingAsync();
        await ResultAsync("settings.set", new { ai = new { providers = new { server = new { address = server.Address, model = "qwen3:8b", contextTokens = 32768 } } } });
        var template = System.Text.Json.Nodes.JsonNode.Parse((await ResultAsync("templates.get", new { templateId = "meeting-minutes" })).GetRawText())!;
        template["providerId"] = "server";
        Assert.Empty(_spy.Events);

        var start = await ResultAsync("generation.start", new { recordingId = id, template });
        Assert.False(start.GetProperty("confirmationRequired").GetBoolean());
        await FinishedAsync(start.GetProperty("jobId").GetString()!);

        var passes = _host.Sink.Payloads(Memento.Core.Bridge.BridgeEventNames.GenerationOutput).Count(e => e.GetProperty("kind").GetString() == "request");
        Assert.True(passes > 1);
        Assert.Equal(passes, server.Requests.Count);
        Assert.All(server.Requests, r => Assert.Equal(("POST", "/v1/chat/completions"), (r.Method, r.Path)));
        var events = _spy.Events;
        Assert.Equal(passes, events.Count(e => e.StartsWith("http ", StringComparison.Ordinal)));
        Assert.All(events.Where(e => e.StartsWith("http ", StringComparison.Ordinal)), e => Assert.Equal($"http POST {server.Address}/v1/chat/completions", e));
        Assert.All(events.Where(e => !e.StartsWith("http ", StringComparison.Ordinal)), e => Assert.Equal(string.Create(CultureInfo.InvariantCulture, $"connect 127.0.0.1:{server.Port}"), e));
        Assert.DoesNotContain(events, e => e.StartsWith("resolve ", StringComparison.Ordinal));
        Assert.Equal(1, _providers.ServerCreated);
        Assert.Equal(0, _providers.CloudCreated);
        Assert.False((await _host.Settings.LoadAsync(CancellationToken.None)).Ai.Enabled);
    }

    /// <summary>The synthetic meeting's stand-in, answering the request the fake server was sent (its schema name says which pass it is).</summary>
    private static string MeetingAnswer(JsonElement body)
    {
        var messages = body.GetProperty("messages").EnumerateArray().ToList();
        var schema = body.TryGetProperty("response_format", out var format) && format.TryGetProperty("json_schema", out var named) ? named.GetProperty("name").GetString() : null;
        var purpose = schema switch
        {
            "verdicts" => "verify.batch",
            "verdict" => "verify.claim",
            null => "verify.claim",
            _ => "map." + schema,
        };
        var request = new AiRequest
        {
            Purpose = purpose,
            System = messages[0].GetProperty("content").GetString()!,
            Messages = [AiMessage.User(messages[^1].GetProperty("content").GetString()!)],
        };
        return new MeetingProvider(AiProviderKind.Server).GenerateAsync(request, null, CancellationToken.None).GetAwaiter().GetResult().Text;
    }

    /// <summary>The synthetic meeting stored as a recording with its transcript (as M4Host does).</summary>
    private async Task<string> MeetingAsync()
    {
        var source = SyntheticMeeting.Manifest();
        var created = await _host.Store.CreateAsync(new Memento.Core.Projects.ProjectCreateRequest(source.Details.Title, "meeting", source.CreatedAt, Memento.Core.Projects.ProjectStates.Ready), CancellationToken.None);
        var manifest = await _host.Store.UpdateAsync(created.Id, m => m with { State = Memento.Core.Projects.ProjectStates.Ready, DurationMs = source.DurationMs, Details = source.Details }, CancellationToken.None);
        await _host.Index.UpsertAsync(manifest, CancellationToken.None);
        await _host.Transcripts.UpdateAsync(created.Id, TranscriptChangeReasons.Transcribed, new HistorySettings(), _ => SyntheticMeeting.Transcript(), CancellationToken.None);
        return created.Id;
    }

    private Task<JsonElement> ResultAsync(string method, object parameters) => _host.ResultAsync(method, JsonSerializer.Serialize(parameters, Web));

    private void Install(params string[] ids)
    {
        foreach (var id in ids)
        {
            var path = _host.Models.PathOf(Catalog.Find(id)!);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllBytes(path, new byte[4]);
            Assert.Equal(ModelCheck.Verified, _host.Models.VerifyAsync(id, CancellationToken.None).GetAwaiter().GetResult());
        }
    }

    private async Task<string> FinishedAsync(string jobId)
    {
        JsonElement final = default;
        await TestRecordings.WaitUntilAsync(
            () =>
            {
                var done = _host.Sink.Payloads("generation.progress").LastOrDefault(e => e.GetProperty("jobId").GetString() == jobId && e.GetProperty("stage").GetString() is "done" or "failed" or "cancelled");
                final = done;
                return done.ValueKind == JsonValueKind.Object;
            },
            "the generation to finish");
        Assert.Equal("done", final.GetProperty("stage").GetString());
        return final.GetProperty("documentId").GetString()!;
    }

    /// <summary>The worker: the live transcript hears each window, Tesseract reads two agenda lines, anything else just ends.</summary>
    private async Task<int> ScriptAsync(WorkerJob job, ScriptedWorkerContext context, CancellationToken cancel)
    {
        lock (_jobs)
        {
            _jobs.Add(job.Kind);
        }

        context.Send(new WorkerReply { Type = WorkerMessageTypes.Ready, Pid = 1 });
        if (job.Kind is not (WorkerJobKinds.Live or WorkerJobKinds.Ocr))
        {
            context.Send(new WorkerReply { Type = WorkerMessageTypes.Result });
            return 0;
        }

        context.Send(new WorkerReply { Type = WorkerMessageTypes.Device, Device = new WorkerDevice("cpu", "CPU", null, null, "test") });
        await foreach (var command in context.Commands.ReadAllAsync(cancel))
        {
            if (command.Type == WorkerMessageTypes.End)
            {
                break;
            }

            if (command.Audio is { } audio)
            {
                context.Send(new WorkerReply { Type = WorkerMessageTypes.Heard, Window = audio.Window, Segments = [new WorkerSegment(audio.StartSeconds + 1, audio.StartSeconds + 3, "Live line.", 0.9, [])] });
            }

            if (command.Image is { } image)
            {
                context.Send(new WorkerReply
                {
                    Type = WorkerMessageTypes.Recognized,
                    Ocr = new OcrRecognized(image.Id, [new OcrWord("1.", 20, 20, 20, 30, 0.95), new OcrWord("Welcome", 50, 20, 120, 30, 0.95), new OcrWord("2.", 20, 70, 20, 30, 0.95), new OcrWord("Budget", 50, 70, 110, 30, 0.95)], 0),
                });
            }
        }

        context.Send(new WorkerReply { Type = WorkerMessageTypes.Result });
        return 0;
    }

    /// <summary>A 24-bit BMP, white with two dark bars (the "lines" the scripted Tesseract reads).</summary>
    private static byte[] Bitmap(int width, int height)
    {
        var stride = ((width * 3) + 3) & ~3;
        var bytes = new byte[54 + (stride * height)];
        "BM"u8.CopyTo(bytes);
        BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(2), bytes.Length);
        BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(10), 54);
        BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(14), 40);
        BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(18), width);
        BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(22), height);
        BinaryPrimitives.WriteInt16LittleEndian(bytes.AsSpan(26), 1);
        BinaryPrimitives.WriteInt16LittleEndian(bytes.AsSpan(28), 24);
        for (var y = 0; y < height; y++)
        {
            var dark = (y / 10) % 5 == 1;
            for (var x = 0; x < width; x++)
            {
                var value = dark && x is > 20 and < 200 ? (byte)20 : (byte)250;
                bytes.AsSpan(54 + (y * stride) + (x * 3), 3).Fill(value);
            }
        }

        return bytes;
    }

